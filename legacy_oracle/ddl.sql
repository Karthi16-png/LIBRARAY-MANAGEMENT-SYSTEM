-- ============================================================================
-- Enterprise Library Management System DDL Script (Oracle 21c)
-- ============================================================================

-- ============================================================================
-- 0. CLEANUP (Drop existing tables in reverse dependency order)
-- ============================================================================
DROP TABLE Fines CASCADE CONSTRAINTS PURGE;
DROP TABLE Loans CASCADE CONSTRAINTS PURGE;
DROP TABLE Book_Copies CASCADE CONSTRAINTS PURGE;
DROP TABLE Book_Authors CASCADE CONSTRAINTS PURGE;
DROP TABLE Books CASCADE CONSTRAINTS PURGE;
DROP TABLE Authors CASCADE CONSTRAINTS PURGE;
DROP TABLE Publishers CASCADE CONSTRAINTS PURGE;
DROP TABLE Categories CASCADE CONSTRAINTS PURGE;
DROP TABLE Users CASCADE CONSTRAINTS PURGE;

-- ============================================================================
-- 1. Users Table (Handles Authentication & Role-Based Access)
-- ============================================================================
CREATE TABLE Users (
    User_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username       VARCHAR2(50) NOT NULL,
    Password_Hash  VARCHAR2(255) NOT NULL,
    Email          VARCHAR2(255) NOT NULL,
    Role           VARCHAR2(20) NOT NULL,
    Account_Status VARCHAR2(20) DEFAULT 'Active' NOT NULL,
    CONSTRAINT chk_users_role CHECK (Role IN ('Admin', 'Librarian', 'Staff', 'Student')),
    CONSTRAINT chk_users_status CHECK (Account_Status IN ('Active', 'Suspended'))
);

-- Case-Insensitive Unique Constraints
CREATE UNIQUE INDEX uq_users_username_ci ON Users (LOWER(Username));
CREATE UNIQUE INDEX uq_users_email_ci ON Users (LOWER(Email));

-- ============================================================================
-- 2. Categories Table
-- ============================================================================
CREATE TABLE Categories (
    Category_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name         VARCHAR2(100) NOT NULL,
    Section_Code VARCHAR2(10),
    CONSTRAINT uq_categories_name UNIQUE (Name)
);

-- ============================================================================
-- 3. Publishers Table
-- ============================================================================
CREATE TABLE Publishers (
    Publisher_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name          VARCHAR2(150) NOT NULL,
    Contact_Email VARCHAR2(255)
);

-- ============================================================================
-- 4. Authors Table
-- ============================================================================
CREATE TABLE Authors (
    Author_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    First_Name VARCHAR2(100) NOT NULL,
    Last_Name  VARCHAR2(100) NOT NULL
);

-- ============================================================================
-- 5. Books Table
-- ============================================================================
CREATE TABLE Books (
    Book_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ISBN             VARCHAR2(20) NOT NULL,
    Title            VARCHAR2(255) NOT NULL,
    Publication_Year NUMBER(4),
    Category_ID      NUMBER NOT NULL,
    Publisher_ID     NUMBER NOT NULL,
    CONSTRAINT uq_books_isbn UNIQUE (ISBN),
    CONSTRAINT fk_books_category FOREIGN KEY (Category_ID) REFERENCES Categories (Category_ID),
    CONSTRAINT fk_books_publisher FOREIGN KEY (Publisher_ID) REFERENCES Publishers (Publisher_ID)
);

-- ============================================================================
-- 6. Book_Authors Table (Resolves Many-to-Many relationship)
-- ============================================================================
CREATE TABLE Book_Authors (
    Book_ID   NUMBER NOT NULL,
    Author_ID NUMBER NOT NULL,
    CONSTRAINT pk_book_authors PRIMARY KEY (Book_ID, Author_ID),
    CONSTRAINT fk_bookauthors_book FOREIGN KEY (Book_ID) REFERENCES Books (Book_ID) ON DELETE CASCADE,
    CONSTRAINT fk_bookauthors_author FOREIGN KEY (Author_ID) REFERENCES Authors (Author_ID)
);

-- ============================================================================
-- 7. Book_Copies Table (Tracks physical inventory)
-- ============================================================================
CREATE TABLE Book_Copies (
    Copy_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Book_ID   NUMBER NOT NULL,
    Status    VARCHAR2(20) DEFAULT 'Available' NOT NULL,
    Condition VARCHAR2(20) DEFAULT 'Good' NOT NULL,
    CONSTRAINT fk_bookcopies_book FOREIGN KEY (Book_ID) REFERENCES Books (Book_ID) ON DELETE CASCADE,
    CONSTRAINT chk_copies_status CHECK (Status IN ('Available', 'Borrowed', 'Lost', 'Maintenance', 'Reserved')),
    CONSTRAINT chk_copies_condition CHECK (Condition IN ('New', 'Good', 'Fair', 'Poor'))
);

-- ============================================================================
-- 8. Loans Table (Tracks check-outs)
-- ============================================================================
CREATE TABLE Loans (
    Loan_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Copy_ID     NUMBER NOT NULL,
    Borrower_ID NUMBER NOT NULL,
    Issued_By   NUMBER NOT NULL,
    Issue_Date  DATE DEFAULT SYSDATE NOT NULL,
    Due_Date    DATE NOT NULL,
    Return_Date DATE,
    CONSTRAINT fk_loans_copy FOREIGN KEY (Copy_ID) REFERENCES Book_Copies (Copy_ID) ON DELETE CASCADE,
    CONSTRAINT fk_loans_borrower FOREIGN KEY (Borrower_ID) REFERENCES Users (User_ID),
    CONSTRAINT fk_loans_issued_by FOREIGN KEY (Issued_By) REFERENCES Users (User_ID),
    CONSTRAINT chk_loans_due_date CHECK (Due_Date >= Issue_Date),
    CONSTRAINT chk_loans_return_date CHECK (Return_Date IS NULL OR Return_Date >= Issue_Date)
);

-- ============================================================================
-- 9. Fines Table
-- ============================================================================
CREATE TABLE Fines (
    Fine_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Loan_ID        NUMBER NOT NULL,
    Fine_Amount    NUMBER(10, 2) NOT NULL,
    Payment_Status VARCHAR2(20) DEFAULT 'Unpaid' NOT NULL,
    Payment_Date   DATE,
    Collected_By   NUMBER,
    CONSTRAINT fk_fines_loan FOREIGN KEY (Loan_ID) REFERENCES Loans (Loan_ID),
    CONSTRAINT fk_fines_collected_by FOREIGN KEY (Collected_By) REFERENCES Users (User_ID),
    CONSTRAINT chk_fines_payment_status CHECK (Payment_Status IN ('Paid', 'Unpaid', 'Waived'))
);

-- ============================================================================
-- Foreign Key Indexes (Prevents Table-Level Lock Escalation During DML)
-- ============================================================================
CREATE INDEX idx_loans_borrower ON Loans (Borrower_ID);
CREATE INDEX idx_loans_copy ON Loans (Copy_ID);
CREATE INDEX idx_fines_loan ON Fines (Loan_ID);

-- Prevent Double-Submit Race Conditions for Active Requests
CREATE UNIQUE INDEX uq_active_requests ON Loan_Requests (
    CASE WHEN Status IN ('Pending', 'Awaiting Pickup') THEN Borrower_ID ELSE NULL END,
    CASE WHEN Status IN ('Pending', 'Awaiting Pickup') THEN Book_ID ELSE NULL END
);

-- ============================================================================
-- 10. Audit_Logs Table (Tracks Administrative & Security Actions)
-- ============================================================================
CREATE TABLE Audit_Logs (
    Log_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Action_Type  VARCHAR2(50) NOT NULL,
    Target_User  VARCHAR2(100),
    Performed_By VARCHAR2(100),
    Log_Date     DATE DEFAULT SYSDATE NOT NULL,
    Details      VARCHAR2(500)
);

